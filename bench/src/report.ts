/**
 * `bench/RESULTS.md`, generated from the files in `bench/results/` and from nothing else. For each
 * mode the newest results file is shown. The guard test regenerates this text and compares it to the
 * committed file, so the table cannot drift from the data it claims to summarise.
 */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { MODE_DESCRIPTIONS } from "./mode-info.ts";
import { resultFileSchema, type ResultFile, type TaskResult } from "./results.ts";
import { MODE_NAMES } from "./task.ts";

export interface LoadedResult {
  file: string;
  result: ResultFile;
}

export function loadResultFiles(dir: string): LoadedResult[] {
  return readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .toSorted()
    .map((file) => {
      const parsed = resultFileSchema.safeParse(JSON.parse(readFileSync(join(dir, file), "utf8")));
      if (!parsed.success) {
        throw new Error(
          `Malformed results file ${file}: ${parsed.error.issues.map((i) => `${i.path.join(".") || "(file)"}: ${i.message}`).join("; ")}`,
        );
      }
      if (!file.endsWith(`-${parsed.data.mode}.json`) || !file.startsWith(parsed.data.date)) {
        throw new Error(
          `Results file ${file} must be named <date>-<mode>.json for its own date and mode`,
        );
      }
      return { file, result: parsed.data };
    });
}

/** The newest file of each mode (file names start with the date, so they sort by it). */
export function latestPerMode(results: readonly LoadedResult[]): LoadedResult[] {
  return MODE_NAMES.flatMap((mode) => {
    const latest = results.findLast((entry) => entry.result.mode === mode);
    return latest ? [latest] : [];
  });
}

const seconds = (ms: number): string => `${(ms / 1000).toFixed(1)}s`;

function detail(task: TaskResult): string {
  if (task.error) return `error: ${task.error.split("\n")[0]?.slice(0, 120) ?? ""}`;
  const failed = task.checks.filter((check) => !check.ok).map((check) => check.name);
  if (task.agentClaimedSuccess && !task.pipelineClaimedSuccess && task.score === "FAIL") {
    return `agent claimed success, the verifier refused it; failed: ${failed.join(", ") || task.outcome}`;
  }
  if (task.control) return failed.length > 0 ? `failed: ${failed.join(", ")}` : "no check failed";
  return task.score === "FAIL" ? `failed: ${failed.join(", ") || task.outcome}` : "";
}

function row(task: TaskResult): string {
  const caught = task.control ? (task.controlCaught ? "caught" : "NOT CAUGHT") : "";
  const result = task.control ? `${task.score} (${caught})` : task.score;
  return `| ${task.id} | ${task.expected} | ${result} | ${task.outcome} | ${seconds(task.durationMs)} | ${task.steps} | ${detail(task)} |`;
}

function section({ file, result }: LoadedResult): string {
  const { summary } = result;
  const header =
    "| Task | Expected | Result | Outcome | Time | Steps | Detail |\n| --- | --- | --- | --- | --- | --- | --- |";
  const tasks = result.tasks.filter((task) => !task.control);
  const controls = result.tasks.filter((task) => task.control);
  const by = summary.byExpected;
  const lines = [
    `## ${result.mode}`,
    "",
    MODE_DESCRIPTIONS[result.mode],
    "",
    `Run on ${result.date} from commit ${result.commit}${result.dirty ? " (working tree had uncommitted changes)" : ""}; autoremediator ${result.autoremediatorVersion}; node ${result.node} on ${result.platform}.${result.model ? ` Model: ${result.model}.` : ""} Source: \`results/${file}\`.`,
    "",
    header,
    ...tasks.map((task) => row(task)),
  ];
  if (controls.length > 0) {
    lines.push(
      "",
      "Controls: deliberately wrong runs that the benchmark must score FAIL.",
      "",
      header,
      ...controls.map((task) => row(task)),
    );
  }
  const tokens = result.tasks.flatMap((task) => (task.tokens ? [task.tokens] : []));
  lines.push(
    "",
    `**${result.mode}: ${summary.pass}/${summary.tasks} PASS** (fixed ${by.fixed.pass}/${by.fixed.total}, unresolved ${by.unresolved.pass}/${by.unresolved.total}, refused ${by.refused.pass}/${by.refused.total}); ${summary.fail} FAIL; false claims of success ${summary.falseClaims}; controls caught ${summary.controls.caught}/${summary.controls.total}; total time ${seconds(summary.totalDurationMs)}${tokens.length > 0 ? `; tokens ${tokens.reduce((sum, t) => sum + t.input, 0)} in / ${tokens.reduce((sum, t) => sum + t.output, 0)} out` : ""}.`,
  );
  return lines.join("\n");
}

export const RESULTS_INTRO = `# Benchmark results

Generated by \`pnpm bench\` from the files in \`bench/results/\`. Do not edit by hand: the guard test
regenerates this file and fails if it differs. See [docs/contributing/benchmark.md](../docs/contributing/benchmark.md)
for what the tasks and modes are, how a task is scored, and how to run a real model.

How to read it:

- **PASS** means the outcome was the correct one for the task, judged by an independent oracle on the
  project the run left behind: for a fix, the vulnerable copy is gone, a fresh \`npm ci\` works, the
  project's own type check and tests pass, and only allowed files changed; for a task with no safe
  fix, the project is untouched, the expected reason was reported, and no fix was claimed.
- **Outcome** is what actually happened: \`fixed\`, \`unresolved\` (no safe version), \`refused\` (policy
  blocked it), \`broken\` (the project changed but is not fixed), or \`false-claim\` (a fix was
  reported that the oracle does not accept).
- **Steps** are model turns in the agent modes and MCP tool calls in \`host-scripted\`; 0 where nothing
  agentic ran. **Time** is the remediation run only (plan, apply, repair), not setup or scoring.
- The scripted modes hand the agent the known-good answer. They measure the harness, not a model.
  Only \`agent-model\` measures a model, and only if it has a results file below.`;

export function renderResults(results: readonly LoadedResult[]): string {
  const latest = latestPerMode(results);
  if (latest.length === 0) return `${RESULTS_INTRO}\n\nNo results yet. Run \`pnpm bench\`.\n`;
  return `${RESULTS_INTRO}\n\n${latest.map((entry) => section(entry)).join("\n\n")}\n`;
}
