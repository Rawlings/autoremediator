/**
 * Change requests commit and push, so they must never run for dry-run/preview/plan flows.
 * Enforced here (not only in the CLI) so SDK, MCP and HTTP callers get the same guarantee.
 */
export function assertChangeRequestAllowed(options: {
  dryRun?: boolean;
  preview?: boolean;
  changeRequest?: { enabled?: boolean };
}): void {
  if (options.changeRequest?.enabled && (options.dryRun || options.preview)) {
    throw new Error(
      "changeRequest cannot be combined with dryRun/preview (or planRemediation): change requests commit and push.",
    );
  }
}

/**
 * Remove option fields that redirect credentials or API traffic. These are host configuration,
 * never something an untrusted MCP/HTTP caller may set. Walks nested objects (e.g. portfolio targets).
 */
export function stripUntrustedChangeRequestFields<T>(value: T): T {
  if (Array.isArray(value)) {
    return value.map((entry) => stripUntrustedChangeRequestFields(entry)) as unknown as T;
  }
  if (typeof value !== "object" || value === null) return value;
  const out: Record<string, unknown> = {};
  for (const [key, entry] of Object.entries(value as Record<string, unknown>)) {
    if (key === "changeRequest" && typeof entry === "object" && entry !== null) {
      const { tokenEnvVar: _t, githubApiUrl: _u, ...rest } = entry as Record<string, unknown>;
      out[key] = rest;
    } else {
      out[key] = stripUntrustedChangeRequestFields(entry);
    }
  }
  return out as T;
}

async function stageRunChanges(cwd: string, reports: RemediationReport[]): Promise<void> {
  // Stage modifications to tracked files only; never sweep up unrelated untracked files.
  await safeExeca("git", ["add", "-u"], { cwd, stdio: "pipe" });
  // New artifacts the run itself produced (generated patch files) are staged explicitly.
  const produced = new Set<string>();
  for (const report of reports) {
    for (const result of report.results) {
      if (!result.patchFilePath) continue;
      const abs = isAbsolute(result.patchFilePath)
        ? result.patchFilePath
        : resolve(cwd, result.patchFilePath);
      const rel = relative(cwd, abs);
      if (rel.startsWith("..") || isAbsolute(rel) || !existsSync(abs)) continue;
      produced.add(rel);
    }
  }
  if (produced.size > 0) {
    await safeExeca("git", ["add", "--", ...produced], { cwd, stdio: "pipe" });
  }
}

interface ChangeRequestPlan {
  cveIds: string[];
  packageNames: string[];
  title: string;
  body: string;
}

function buildPlan(reports: RemediationReport[]): ChangeRequestPlan {
  const cveIds = [...new Set(reports.map((report) => report.cveId))];
  const packageNames = [
    ...new Set(reports.flatMap((report) => report.results.map((result) => result.packageName))),
  ];

  // A freshness step upgrades a dependency to stay current: it is not a security remediation.
  if (reports.length > 0 && reports.every((report) => report.cveId.startsWith("FRESHNESS-"))) {
    const moves = reports.flatMap((report) =>
      report.results.map(
        (result) => `${result.packageName} ${result.fromVersion} -> ${result.toVersion ?? "?"}`,
      ),
    );
    return {
      cveIds,
      packageNames,
      title: `dependency freshness: ${moves.join(", ")}`,
      body: [
        "Automated dependency freshness step generated by autoremediator.",
        "",
        ...moves.map((move) => `- ${move}`),
      ].join("\n"),
    };
  }

  const titleSuffix = cveIds.length === 1 ? cveIds[0]! : `${cveIds.length} CVEs`;
  const title = `security remediation: ${titleSuffix}`;
  const body = [
    "Automated remediation generated by autoremediator.",
    "",
    `CVEs: ${cveIds.join(", ")}`,
    `Packages: ${packageNames.join(", ")}`,
  ].join("\n");

  return {
    cveIds,
    packageNames,
    title,
    body,
  };
}

function resolveProvider(options: ChangeRequestOptions): ChangeRequestProvider {
  const provider = options.provider ?? "github";
  if (!CHANGE_REQUEST_PROVIDER_VALUES.includes(provider)) {
    throw new Error(
      `Unsupported changeRequest.provider: "${provider}". Supported values: ${CHANGE_REQUEST_PROVIDER_VALUES.join(", ")}`,
    );
  }
  return provider;
}

function resolveGrouping(options: ChangeRequestOptions): ChangeRequestGrouping {
  const allowed: ChangeRequestGrouping[] = ["all", "per-cve", "per-package", "by-severity"];
  if (options.grouping && !allowed.includes(options.grouping)) {
    throw new Error(
      `Unsupported changeRequest.grouping: "${options.grouping}". Supported values: ${allowed.join(", ")}`,
    );
  }
  return options.grouping ?? "all";
}

export function groupReports(
  reports: RemediationReport[],
  grouping: ChangeRequestGrouping,
): RemediationReport[][] {
  if (reports.length === 0) return [];
  if (grouping === "all") {
    return [reports];
  }

  if (grouping === "per-cve") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const key = report.cveId.toUpperCase();
      const list = map.get(key) ?? [];
      list.push(report);
      map.set(key, list);
    }
    return [...map.values()];
  }

  if (grouping === "per-package") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const pkgs = new Set(report.results.map((r) => r.packageName));
      if (pkgs.size === 0) {
        const list = map.get("misc") ?? [];
        list.push(report);
        map.set("misc", list);
      } else {
        for (const pkg of pkgs) {
          const list = map.get(pkg) ?? [];
          list.push(report);
          map.set(pkg, list);
        }
      }
    }
    return [...map.values()];
  }

  if (grouping === "by-severity") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const sev = report.cveDetails?.severity ?? "UNKNOWN";
      const list = map.get(sev) ?? [];
      list.push(report);
      map.set(sev, list);
    }
    return [...map.values()];
  }

  return [reports];
}

async function detectCurrentBranch(cwd: string): Promise<string> {
  const result = await safeExeca("git", ["rev-parse", "--abbrev-ref", "HEAD"], {
    cwd,
    stdio: "pipe",
  });
  return result.stdout.trim();
}

async function ensureRepoHasChanges(cwd: string): Promise<boolean> {
  const diff = await safeExeca("git", ["status", "--porcelain"], {
    cwd,
    stdio: "pipe",
  });
  return diff.stdout.trim().length > 0;
}

async function readOriginUrl(cwd: string): Promise<string> {
  const result = await safeExeca("git", ["config", "--get", "remote.origin.url"], {
    cwd,
    stdio: "pipe",
  }).catch(() => ({ stdout: "" }));
  return result.stdout.trim();
}

/** The URL a named remote pushes to, as configured (before any `insteadOf` rewriting). */
async function readRemoteUrl(cwd: string, remote: string): Promise<string> {
  for (const key of [`remote.${remote}.pushurl`, `remote.${remote}.url`]) {
    const result = await safeExeca("git", ["config", "--get", key], { cwd, stdio: "pipe" }).catch(
      () => ({ stdout: "" }),
    );
    if (result.stdout.trim()) return result.stdout.trim();
  }
  return "";
}

async function detectRepoFromRemote(cwd: string): Promise<string | undefined> {
  const url = await readOriginUrl(cwd);
  const match = /[:/]([^/]+)\/([^/]+?)(?:\.git)?$/.exec(url);
  if (match) {
    return `${match[1]}/${match[2]}`;
  }
  return undefined;
}

async function ensureRepoHasStagedChanges(cwd: string): Promise<boolean> {
  const result = await safeExeca("git", ["diff", "--cached", "--name-only"], {
    cwd,
    stdio: "pipe",
  }).catch(() => ({ stdout: "" }));
  return result.stdout.trim().length > 0;
}

async function createGitHubRequest(params: {
  cwd: string;
  repository?: string;
  head: string;
  base: string;
  title: string;
  body: string;
  draft?: boolean;
  token?: string;
  githubApiUrl?: string;
}): Promise<string | undefined> {
  const token = params.token ?? process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;

  let repository = params.repository;
  if (!repository) {
    repository = await detectRepoFromRemote(params.cwd);
  }

  if (token && repository) {
    const [owner, repo] = repository.split("/");
    const baseUrl =
      (params.githubApiUrl ? trimChar(params.githubApiUrl, "/", "end") : undefined) ||
      "https://api.github.com";
    const endpoint = `${baseUrl}/repos/${owner}/${repo}/pulls`;
    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        authorization: `Bearer ${token}`,
        accept: "application/vnd.github+json",
        "content-type": "application/json",
        "user-agent": "autoremediator",
        "x-github-api-version": "2022-11-28",
      },
      body: JSON.stringify({
        title: params.title,
        head: params.head,
        base: params.base,
        body: params.body,
        draft: Boolean(params.draft),
      }),
    });

    if (!response.ok) {
      const errText = await response.text().catch(() => "");
      if (response.status === 422 && /already exists/i.test(errText)) {
        // A re-run updated the branch of an open pull request: point at that one instead of failing.
        const found = await fetch(
          `${baseUrl}/repos/${owner}/${repo}/pulls?state=open&head=${encodeURIComponent(`${owner}:${params.head}`)}`,
          {
            headers: {
              authorization: `Bearer ${token}`,
              accept: "application/vnd.github+json",
              "user-agent": "autoremediator",
              "x-github-api-version": "2022-11-28",
            },
          },
        ).catch(() => undefined);
        const pulls = found?.ok
          ? ((await found.json().catch(() => [])) as Array<{ html_url?: string }>)
          : [];
        return pulls[0]?.html_url;
      }
      throw new Error(`GitHub API create pull request failed (${response.status}): ${errText}`);
    }

    const data = (await response.json()) as { html_url?: string };
    return data.html_url || undefined;
  }

  const args = [
    "pr",
    "create",
    "--head",
    params.head,
    "--base",
    params.base,
    "--title",
    params.title,
    "--body",
    params.body,
  ];
  if (params.repository) {
    args.push("--repo", params.repository);
  }
  if (params.draft) {
    args.push("--draft");
  }

  try {
    const result = await safeExeca("gh", args, {
      cwd: params.cwd,
      stdio: "pipe",
    });
    return result.stdout.trim() || undefined;
  } catch (error) {
    if (!/already exists/i.test(errorMessage(error))) throw error;
    const view = await safeExeca(
      "gh",
      ["pr", "view", params.head, "--json", "url", "--jq", ".url"],
      {
        cwd: params.cwd,
        stdio: "pipe",
      },
    ).catch(() => undefined);
    return view?.stdout.trim() || undefined;
  }
}

async function createGitLabRequest(params: {
  cwd: string;
  repository?: string;
  source: string;
  target: string;
  title: string;
  body: string;
  draft?: boolean;
  token?: string;
}): Promise<string | undefined> {
  const remote = parseRemoteUrl(await readOriginUrl(params.cwd));
  const repository =
    params.repository ?? (remote ? repositoryFromRemote("gitlab", remote) : undefined);
  const apiUrl =
    process.env.CI_API_V4_URL || (remote ? `${remote.scheme}://${remote.host}/api/v4` : undefined);

  // With a token and a resolvable project, use the REST API (works in any CI image, no glab needed).
  if (params.token && repository && apiUrl) {
    return createGitLabMergeRequestViaApi({
      apiUrl,
      repository,
      head: params.source,
      base: params.target,
      title: params.title,
      body: params.body,
      draft: params.draft,
      token: params.token,
    });
  }

  const args = [
    "mr",
    "create",
    "--source-branch",
    params.source,
    "--target-branch",
    params.target,
    "--title",
    params.title,
    "--description",
    params.body,
  ];
  if (params.repository) {
    args.push("-R", params.repository);
  }
  if (params.draft) {
    args.push("--draft");
  }

  try {
    const result = await safeExeca("glab", args, {
      cwd: params.cwd,
      stdio: "pipe",
    });
    return result.stdout.trim() || undefined;
  } catch (error) {
    // The branch update already refreshed the open merge request.
    if (/already exists/i.test(errorMessage(error))) return undefined;
    throw error;
  }
}

/** `git` arguments that authenticate over HTTPS with the token, in the way the host expects. */
function withAuth(
  provider: ChangeRequestProvider,
  token: string | undefined,
  args: string[],
): string[] {
  if (!token) return args;
  return ["-c", `http.extraheader=${buildPushAuthHeader(provider, token)}`, ...args];
}

/**
 * Commits on `ref` that are not in HEAD and were not made by a previous change-request run
 * (our bot identity plus a `Fixes-CVE:` or `Autoremediator-Change:` trailer). Any such commit is somebody's work.
 */
async function foreignCommits(
  cwd: string,
  ref: string,
  provider: ChangeRequestProvider,
): Promise<number> {
  const result = await safeExeca("git", ["log", ref, "--not", "HEAD", "--format=%ae%x1f%B%x1e"], {
    cwd,
    stdio: "pipe",
  }).catch(() => ({ stdout: "" }));
  let foreign = 0;
  for (const entry of result.stdout.split("\u001e")) {
    const text = entry.trim();
    if (!text) continue;
    const [email = "", message = ""] = text.split("\u001f");
    if (
      email.trim() !== commitIdentity(provider).email ||
      !/^(?:Fixes-CVE|Autoremediator-Change): /m.test(message)
    ) {
      foreign += 1;
    }
  }
  return foreign;
}

interface ExistingBranch {
  /** Where the branch already exists on the remote, if it does. */
  remoteSha?: string;
  /** Someone else's commits are on it (locally or remotely), so it must not be overwritten. */
  foreign: boolean;
}

/** Look at the branch a re-run would reuse before touching it. */
async function inspectExistingBranch(
  provider: ChangeRequestProvider,
  cwd: string,
  remote: string,
  branch: string,
  token: string | undefined,
): Promise<ExistingBranch> {
  let foreign = false;
  const local = await safeExeca(
    "git",
    ["rev-parse", "--verify", "--quiet", `refs/heads/${branch}`],
    {
      cwd,
      stdio: "pipe",
    },
  ).catch(() => undefined);
  if (local?.stdout.trim()) {
    foreign = (await foreignCommits(cwd, `refs/heads/${branch}`, provider)) > 0;
  }

  const listed = await safeExeca(
    "git",
    withAuth(provider, token, ["ls-remote", "--heads", "--", remote, `refs/heads/${branch}`]),
    {
      cwd,
      stdio: "pipe",
    },
  ).catch(() => undefined);
  const remoteSha = /^([0-9a-f]{40})\s/.exec((listed?.stdout ?? "").trim())?.[1];
  if (remoteSha) {
    const fetched = await safeExeca(
      "git",
      withAuth(provider, token, ["fetch", "--", remote, `refs/heads/${branch}`]),
      {
        cwd,
        stdio: "pipe",
      },
    ).then(
      () => true,
      () => false,
    );
    // If we cannot read what is there, assume the worst rather than overwrite it.
    foreign = foreign || !fetched || (await foreignCommits(cwd, "FETCH_HEAD", provider)) > 0;
  }
  return { ...(remoteSha ? { remoteSha } : {}), foreign };
}

async function createBitbucketRequest(params: {
  cwd: string;
  repository?: string;
  head: string;
  base: string;
  title: string;
  body: string;
  draft?: boolean;
  token: string;
}): Promise<string | undefined> {
  const remote = parseRemoteUrl(await readOriginUrl(params.cwd));
  const repository =
    params.repository ?? (remote ? repositoryFromRemote("bitbucket", remote) : undefined);
  if (!repository) {
    throw new Error(
      "Could not determine the Bitbucket repository from remote.origin.url; set changeRequest.repository to workspace/repo.",
    );
  }
  return createBitbucketPullRequest({ ...params, repository });
}

async function createAzureDevOpsRequest(params: {
  cwd: string;
  repository?: string;
  head: string;
  base: string;
  title: string;
  body: string;
  draft?: boolean;
  token: string;
}): Promise<string | undefined> {
  const remote = parseRemoteUrl(await readOriginUrl(params.cwd));
  const repository =
    params.repository ?? (remote ? repositoryFromRemote("azure-devops", remote) : undefined);
  if (!repository) {
    throw new Error(
      "Could not determine the Azure DevOps repository from remote.origin.url; set changeRequest.repository to organization/project/repo.",
    );
  }
  // SSH remotes use ssh.dev.azure.com; the REST API lives on dev.azure.com.
  const host = remote?.host.replace(/^(?:vs-)?ssh\./, "");
  return createAzureDevOpsPullRequest({
    ...params,
    repository,
    baseUrl: remote && host ? `${remote.scheme}://${host}` : undefined,
  });
}

async function openChangeRequest(params: {
  provider: ChangeRequestProvider;
  cwd: string;
  repository?: string;
  head: string;
  base: string;
  title: string;
  body: string;
  draft?: boolean;
  token?: string;
  githubApiUrl?: string;
}): Promise<string | undefined> {
  const { provider, token, ...rest } = params;
  if (provider === "github") {
    return createGitHubRequest({ ...rest, token });
  }
  try {
    return await openOtherHostRequest(params);
  } catch (error) {
    // A re-run updates the branch of a request that is still open; that is not a failure.
    if (isExistingRequestError(errorMessage(error))) return undefined;
    throw error;
  }
}

/** Hosts answer a duplicate request differently; these are the phrases seen in their API errors. */
export function isExistingRequestError(message: string): boolean {
  return /already exists|already an open|active pull request|another open merge request/i.test(
    message,
  );
}

async function openOtherHostRequest(
  params: Parameters<typeof openChangeRequest>[0],
): Promise<string | undefined> {
  const { provider, token, ...rest } = params;
  if (provider === "gitlab") {
    return createGitLabRequest({
      cwd: rest.cwd,
      repository: rest.repository,
      source: rest.head,
      target: rest.base,
      title: rest.title,
      body: rest.body,
      draft: rest.draft,
      token,
    });
  }
  if (provider === "bitbucket") {
    return createBitbucketRequest({ ...rest, token: token! });
  }
  return createAzureDevOpsRequest({ ...rest, token: token! });
}

export async function createChangeRequestsForReports(params: {
  cwd: string;
  options: ChangeRequestOptions;
  reports: RemediationReport[];
}): Promise<ChangeRequestResult[]> {
  const { cwd, options, reports } = params;
  const provider = resolveProvider(options);
  const grouping = resolveGrouping(options);
  const groups = groupReports(reports, grouping);

  if (groups.length === 0) {
    return [];
  }

  const results: ChangeRequestResult[] = [];
  const token = resolveChangeRequestToken(provider, options);

  // A caller-supplied branch reaches `git checkout`: it must not read as an option (git itself never names a branch "-...").
  if (options.baseBranch !== undefined) assertSafeGitRef("baseBranch", options.baseBranch);
  const baseBranch = options.baseBranch ?? (await detectCurrentBranch(cwd).catch(() => "main"));
  const branchPrefix = options.branchPrefix ?? "autoremediator";
  const pushRemote = options.pushRemote ?? "origin";
  if (options.pushRemote && !/^[a-zA-Z0-9._][a-zA-Z0-9._-]*$/.test(options.pushRemote)) {
    throw new Error(`Invalid pushRemote value: ${options.pushRemote}`);
  }

  // The token goes to the push remote (and, off GitHub, to the API host the origin names): check both before using it.
  let destination: { pushToken: string | undefined; refusal: string | undefined } | undefined;
  const tokenDestination = async (): Promise<{
    pushToken: string | undefined;
    refusal: string | undefined;
  }> => {
    if (destination) return destination;
    if (!token) {
      destination = { pushToken: undefined, refusal: undefined };
      return destination;
    }
    const explicitToken = Boolean(
      options.token || (options.tokenEnvVar && process.env[options.tokenEnvVar]),
    );
    const pushCheck = checkTokenDestination({
      provider,
      remoteUrl: await readRemoteUrl(cwd, pushRemote),
      explicitToken,
      githubApiUrl: options.githubApiUrl,
      forPush: true,
    });
    const apiCheck =
      provider === "github"
        ? undefined
        : checkTokenDestination({ provider, remoteUrl: await readOriginUrl(cwd), explicitToken });
    destination = {
      pushToken: pushCheck.send ? token : undefined,
      refusal: pushCheck.refusal ?? apiCheck?.refusal,
    };
    return destination;
  };
  if (options.repository && !isValidRepositoryForProvider(provider, options.repository)) {
    throw new Error(`Invalid repository format: ${options.repository}`);
  }

  for (const group of groups) {
    const plan = buildPlan(group);
    const titlePrefix = options.titlePrefix?.trim().slice(0, 200);
    const bodyFooter = options.bodyFooter ? options.bodyFooter.slice(0, 2000) : undefined;
    const title = titlePrefix ? `${titlePrefix} ${plan.title}` : plan.title;
    const body = bodyFooter ? `${plan.body}\n\n${bodyFooter}` : plan.body;

    const hasChanges = await ensureRepoHasChanges(cwd).catch(() => false);
    if (!hasChanges) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: "No repository changes to include in change request.",
      });
      continue;
    }

    const { pushToken, refusal: tokenRefusal } = await tokenDestination();
    if (tokenRefusal) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: tokenRefusal,
      });
      continue;
    }

    const branchName = deterministicBranchName(branchPrefix, plan.cveIds, plan.packageNames);
    let branchCreated = false;

    const existing = await inspectExistingBranch(provider, cwd, pushRemote, branchName, pushToken);
    if (existing.foreign) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: `Branch ${branchName} already exists with commits that autoremediator did not make; not overwriting it.`,
      });
      continue;
    }

    try {
      if ((provider === "bitbucket" || provider === "azure-devops") && !token) {
        throw new Error(
          `A token is required to create a ${provider} pull request: set changeRequest.token/tokenEnvVar or the provider's token environment variable.`,
        );
      }
      // -B: a re-run for the same findings restarts the branch from the current base.
      await safeExeca("git", ["checkout", "-B", branchName], { cwd, stdio: "pipe" });
      branchCreated = true;
      await stageRunChanges(cwd, group);

      const hasStaged = await ensureRepoHasStagedChanges(cwd);
      if (!hasStaged) {
        results.push({
          provider,
          grouping,
          repository: options.repository,
          branchName: "",
          title,
          body,
          created: false,
          cveIds: plan.cveIds,
          packageNames: plan.packageNames,
          error: "No repository changes to include in change request.",
        });
        continue;
      }

      const identity = commitIdentity(provider);
      await safeExeca(
        "git",
        [
          "-c",
          `user.name=${identity.name}`,
          "-c",
          `user.email=${identity.email}`,
          "commit",
          "-m",
          commitMessage(title, group),
        ],
        { cwd, stdio: "pipe" },
      );

      // A re-run replaces only the commit a previous run pushed, and only if nobody moved the branch since.
      const pushArgs = withAuth(
        provider,
        pushToken,
        existing.remoteSha
          ? [
              "push",
              `--force-with-lease=refs/heads/${branchName}:${existing.remoteSha}`,
              "-u",
              "--",
              pushRemote,
              branchName,
            ]
          : ["push", "-u", "--", pushRemote, branchName],
      );
      await safeExeca("git", pushArgs, { cwd, stdio: "pipe" });

      const url = await openChangeRequest({
        provider,
        cwd,
        repository: options.repository,
        head: branchName,
        base: baseBranch,
        title,
        body,
        draft: options.draft,
        token,
        githubApiUrl: options.githubApiUrl,
      });

      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName,
        title,
        body,
        created: true,
        ...(existing.remoteSha ? { updated: true } : {}),
        draft: options.draft,
        url,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
      });
    } catch (error) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        draft: options.draft,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: redactSecrets(errorMessage(error)),
      });
    } finally {
      if (branchCreated) {
        await safeExeca("git", ["checkout", baseBranch], { cwd, stdio: "pipe" }).catch(() => {});
      }
    }
  }

  return results;
}
