/**
 * Change requests commit and push, so they must never run for dry-run/preview/plan flows.
 * Enforced here (not only in the CLI) so SDK, MCP and HTTP callers get the same guarantee.
 */
export function assertChangeRequestAllowed(options: {
  dryRun?: boolean;
  preview?: boolean;
  changeRequest?: { enabled?: boolean };
}): void {
  if (options.changeRequest?.enabled && (options.dryRun || options.preview)) {
    throw new Error(
      "changeRequest cannot be combined with dryRun/preview (or planRemediation): change requests commit and push.",
    );
  }
}

/**
 * Remove option fields that redirect credentials or API traffic. These are host configuration,
 * never something an untrusted MCP/HTTP caller may set. Walks nested objects (e.g. portfolio targets).
 */
export function stripUntrustedChangeRequestFields<T>(value: T): T {
  if (Array.isArray(value)) {
    return value.map((entry) => stripUntrustedChangeRequestFields(entry)) as unknown as T;
  }
  if (typeof value !== "object" || value === null) return value;
  const out: Record<string, unknown> = {};
  for (const [key, entry] of Object.entries(value as Record<string, unknown>)) {
    if (key === "changeRequest" && typeof entry === "object" && entry !== null) {
      const { tokenEnvVar: _t, githubApiUrl: _u, ...rest } = entry as Record<string, unknown>;
      out[key] = rest;
    } else {
      out[key] = stripUntrustedChangeRequestFields(entry);
    }
  }
  return out as T;
}

async function stageRunChanges(cwd: string, reports: RemediationReport[]): Promise<void> {
  // Stage modifications to tracked files only; never sweep up unrelated untracked files.
  await safeExeca("git", ["add", "-u"], { cwd, stdio: "pipe" });
  // New artifacts the run itself produced (generated patch files) are staged explicitly.
  const produced = new Set<string>();
  for (const report of reports) {
    for (const result of report.results) {
      if (!result.patchFilePath) continue;
      const abs = isAbsolute(result.patchFilePath)
        ? result.patchFilePath
        : resolve(cwd, result.patchFilePath);
      const rel = relative(cwd, abs);
      if (rel.startsWith("..") || isAbsolute(rel) || !existsSync(abs)) continue;
      produced.add(rel);
    }
  }
  if (produced.size > 0) {
    await safeExeca("git", ["add", "--", ...produced], { cwd, stdio: "pipe" });
  }
}

interface ChangeRequestPlan {
  cveIds: string[];
  packageNames: string[];
  title: string;
  body: string;
}

function buildPlan(reports: RemediationReport[]): ChangeRequestPlan {
  const cveIds = [...new Set(reports.map((report) => report.cveId))];
  const packageNames = [
    ...new Set(reports.flatMap((report) => report.results.map((result) => result.packageName))),
  ];

  const titleSuffix = cveIds.length === 1 ? cveIds[0]! : `${cveIds.length} CVEs`;
  const title = `security remediation: ${titleSuffix}`;
  const body = [
    "Automated remediation generated by autoremediator.",
    "",
    `CVEs: ${cveIds.join(", ")}`,
    `Packages: ${packageNames.join(", ")}`,
  ].join("\n");

  return {
    cveIds,
    packageNames,
    title,
    body,
  };
}

function resolveProvider(options: ChangeRequestOptions): "github" | "gitlab" {
  return options.provider ?? "github";
}

function resolveGrouping(options: ChangeRequestOptions): ChangeRequestGrouping {
  const allowed: ChangeRequestGrouping[] = ["all", "per-cve", "per-package", "by-severity"];
  if (options.grouping && !allowed.includes(options.grouping)) {
    throw new Error(
      `Unsupported changeRequest.grouping: "${options.grouping}". Supported values: ${allowed.join(", ")}`,
    );
  }
  return options.grouping ?? "all";
}

export function groupReports(
  reports: RemediationReport[],
  grouping: ChangeRequestGrouping,
): RemediationReport[][] {
  if (reports.length === 0) return [];
  if (grouping === "all") {
    return [reports];
  }

  if (grouping === "per-cve") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const key = report.cveId.toUpperCase();
      const list = map.get(key) ?? [];
      list.push(report);
      map.set(key, list);
    }
    return [...map.values()];
  }

  if (grouping === "per-package") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const pkgs = new Set(report.results.map((r) => r.packageName));
      if (pkgs.size === 0) {
        const list = map.get("misc") ?? [];
        list.push(report);
        map.set("misc", list);
      } else {
        for (const pkg of pkgs) {
          const list = map.get(pkg) ?? [];
          list.push(report);
          map.set(pkg, list);
        }
      }
    }
    return [...map.values()];
  }

  if (grouping === "by-severity") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const sev = report.cveDetails?.severity ?? "UNKNOWN";
      const list = map.get(sev) ?? [];
      list.push(report);
      map.set(sev, list);
    }
    return [...map.values()];
  }

  return [reports];
}

async function detectCurrentBranch(cwd: string): Promise<string> {
  const result = await safeExeca("git", ["rev-parse", "--abbrev-ref", "HEAD"], {
    cwd,
    stdio: "pipe",
  });
  return result.stdout.trim();
}

async function ensureRepoHasChanges(cwd: string): Promise<boolean> {
  const diff = await safeExeca("git", ["status", "--porcelain"], {
    cwd,
    stdio: "pipe",
  });
  return diff.stdout.trim().length > 0;
}

async function detectRepoFromRemote(cwd: string): Promise<string | undefined> {
  const result = await safeExeca("git", ["config", "--get", "remote.origin.url"], {
    cwd,
    stdio: "pipe",
  }).catch(() => ({ stdout: "" }));
  const url = result.stdout.trim();
  const match = /[:/]([^/]+)\/([^/]+?)(?:\.git)?$/.exec(url);
  if (match) {
    return `${match[1]}/${match[2]}`;
  }
  return undefined;
}

async function ensureRepoHasStagedChanges(cwd: string): Promise<boolean> {
  const result = await safeExeca("git", ["diff", "--cached", "--name-only"], {
    cwd,
    stdio: "pipe",
  }).catch(() => ({ stdout: "" }));
  return result.stdout.trim().length > 0;
}

async function createGitHubRequest(params: {
  cwd: string;
  repository?: string;
  head: string;
  base: string;
  title: string;
  body: string;
  draft?: boolean;
  token?: string;
  githubApiUrl?: string;
}): Promise<string | undefined> {
  const token = params.token ?? process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;

  let repository = params.repository;
  if (!repository) {
    repository = await detectRepoFromRemote(params.cwd);
  }

  if (token && repository) {
    const [owner, repo] = repository.split("/");
    const baseUrl =
      (params.githubApiUrl ? trimChar(params.githubApiUrl, "/", "end") : undefined) ||
      "https://api.github.com";
    const endpoint = `${baseUrl}/repos/${owner}/${repo}/pulls`;
    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        authorization: `Bearer ${token}`,
        accept: "application/vnd.github+json",
        "content-type": "application/json",
        "user-agent": "autoremediator",
        "x-github-api-version": "2022-11-28",
      },
      body: JSON.stringify({
        title: params.title,
        head: params.head,
        base: params.base,
        body: params.body,
        draft: Boolean(params.draft),
      }),
    });

    if (!response.ok) {
      const errText = await response.text().catch(() => "");
      if (response.status === 422 && /already exists/i.test(errText)) {
        // A re-run updated the branch of an open pull request: point at that one instead of failing.
        const found = await fetch(
          `${baseUrl}/repos/${owner}/${repo}/pulls?state=open&head=${encodeURIComponent(`${owner}:${params.head}`)}`,
          {
            headers: {
              authorization: `Bearer ${token}`,
              accept: "application/vnd.github+json",
              "user-agent": "autoremediator",
              "x-github-api-version": "2022-11-28",
            },
          },
        ).catch(() => undefined);
        const pulls = found?.ok ? ((await found.json().catch(() => [])) as Array<{ html_url?: string }>) : [];
        return pulls[0]?.html_url;
      }
      throw new Error(`GitHub API create pull request failed (${response.status}): ${errText}`);
    }

    const data = (await response.json()) as { html_url?: string };
    return data.html_url || undefined;
  }

  const args = [
    "pr",
    "create",
    "--head",
    params.head,
    "--base",
    params.base,
    "--title",
    params.title,
    "--body",
    params.body,
  ];
  if (params.repository) {
    args.push("--repo", params.repository);
  }
  if (params.draft) {
    args.push("--draft");
  }

  try {
    const result = await safeExeca("gh", args, {
      cwd: params.cwd,
      stdio: "pipe",
    });
    return result.stdout.trim() || undefined;
  } catch (error) {
    if (!/already exists/i.test(error instanceof Error ? error.message : String(error))) throw error;
    const view = await safeExeca("gh", ["pr", "view", params.head, "--json", "url", "--jq", ".url"], {
      cwd: params.cwd,
      stdio: "pipe",
    }).catch(() => undefined);
    return view?.stdout.trim() || undefined;
  }
}

async function createGitLabRequest(params: {
  cwd: string;
  repository?: string;
  source: string;
  target: string;
  title: string;
  body: string;
  draft?: boolean;
}): Promise<string | undefined> {
  const args = [
    "mr",
    "create",
    "--source-branch",
    params.source,
    "--target-branch",
    params.target,
    "--title",
    params.title,
    "--description",
    params.body,
  ];
  if (params.repository) {
    args.push("-R", params.repository);
  }
  if (params.draft) {
    args.push("--draft");
  }

  try {
    const result = await safeExeca("glab", args, {
      cwd: params.cwd,
      stdio: "pipe",
    });
    return result.stdout.trim() || undefined;
  } catch (error) {
    // The branch update already refreshed the open merge request.
    if (/already exists/i.test(error instanceof Error ? error.message : String(error))) return undefined;
    throw error;
  }
}

const BOT_NAME = "autoremediator[bot]";
const BOT_EMAIL = "41898282+github-actions[bot]@users.noreply.github.com";

/** `git` arguments that authenticate over HTTPS with the token, when there is one. */
function withAuth(token: string | undefined, args: string[]): string[] {
  if (!token) return args;
  const header = `AUTHORIZATION: basic ${Buffer.from(`x-access-token:${token}`).toString("base64")}`;
  return ["-c", `http.extraheader=${header}`, ...args];
}

/**
 * Commits on `ref` that are not in HEAD and were not made by a previous change-request run
 * (our bot identity plus a `Fixes-CVE:` trailer). Any such commit is somebody's work.
 */
async function foreignCommits(cwd: string, ref: string): Promise<number> {
  const result = await safeExeca(
    "git",
    ["log", ref, "--not", "HEAD", "--format=%ae%x1f%B%x1e"],
    { cwd, stdio: "pipe" },
  ).catch(() => ({ stdout: "" }));
  let foreign = 0;
  for (const entry of result.stdout.split("\u001e")) {
    const text = entry.trim();
    if (!text) continue;
    const [email = "", message = ""] = text.split("\u001f");
    if (email.trim() !== BOT_EMAIL || !/^Fixes-CVE: /m.test(message)) foreign += 1;
  }
  return foreign;
}

interface ExistingBranch {
  /** Where the branch already exists on the remote, if it does. */
  remoteSha?: string;
  /** Someone else's commits are on it (locally or remotely), so it must not be overwritten. */
  foreign: boolean;
}

/** Look at the branch a re-run would reuse before touching it. */
async function inspectExistingBranch(
  cwd: string,
  remote: string,
  branch: string,
  token: string | undefined,
): Promise<ExistingBranch> {
  let foreign = false;
  const local = await safeExeca("git", ["rev-parse", "--verify", "--quiet", `refs/heads/${branch}`], {
    cwd,
    stdio: "pipe",
  }).catch(() => undefined);
  if (local?.stdout.trim()) {
    foreign = (await foreignCommits(cwd, `refs/heads/${branch}`)) > 0;
  }

  const listed = await safeExeca("git", withAuth(token, ["ls-remote", "--heads", remote, `refs/heads/${branch}`]), {
    cwd,
    stdio: "pipe",
  }).catch(() => undefined);
  const remoteSha = /^([0-9a-f]{40})\s/.exec((listed?.stdout ?? "").trim())?.[1];
  if (remoteSha) {
    const fetched = await safeExeca("git", withAuth(token, ["fetch", remote, `refs/heads/${branch}`]), {
      cwd,
      stdio: "pipe",
    }).then(
      () => true,
      () => false,
    );
    // If we cannot read what is there, assume the worst rather than overwrite it.
    foreign = foreign || !fetched || (await foreignCommits(cwd, "FETCH_HEAD")) > 0;
  }
  return { ...(remoteSha ? { remoteSha } : {}), foreign };
}

export async function createChangeRequestsForReports(params: {
  cwd: string;
  options: ChangeRequestOptions;
  reports: RemediationReport[];
}): Promise<ChangeRequestResult[]> {
  const { cwd, options, reports } = params;
  const provider = resolveProvider(options);
  const grouping = resolveGrouping(options);
  const groups = groupReports(reports, grouping);

  if (groups.length === 0) {
    return [];
  }

  const results: ChangeRequestResult[] = [];
  const token =
    options.token ??
    (options.tokenEnvVar ? process.env[options.tokenEnvVar] : undefined) ??
    process.env.GITHUB_TOKEN ??
    process.env.GH_TOKEN;

  const baseBranch = options.baseBranch ?? (await detectCurrentBranch(cwd).catch(() => "main"));
  const branchPrefix = options.branchPrefix ?? "autoremediator";
  const pushRemote = options.pushRemote ?? "origin";
  if (options.pushRemote && !/^[a-zA-Z0-9._-]+$/.test(options.pushRemote)) {
    throw new Error(`Invalid pushRemote value: ${options.pushRemote}`);
  }
  if (options.repository && !/^[a-zA-Z0-9._-]+\/[a-zA-Z0-9._-]+$/.test(options.repository)) {
    throw new Error(`Invalid repository format: ${options.repository}`);
  }

  for (const group of groups) {
    const plan = buildPlan(group);
    const titlePrefix = options.titlePrefix?.trim().slice(0, 200);
    const bodyFooter = options.bodyFooter ? options.bodyFooter.slice(0, 2000) : undefined;
    const title = titlePrefix ? `${titlePrefix} ${plan.title}` : plan.title;
    const body = bodyFooter ? `${plan.body}\n\n${bodyFooter}` : plan.body;

    const hasChanges = await ensureRepoHasChanges(cwd).catch(() => false);
    if (!hasChanges) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: "No repository changes to include in change request.",
      });
      continue;
    }

    const branchName = deterministicBranchName(branchPrefix, plan.cveIds, plan.packageNames);
    let branchCreated = false;

    const existing = await inspectExistingBranch(cwd, pushRemote, branchName, token);
    if (existing.foreign) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: `Branch ${branchName} already exists with commits that autoremediator did not make; not overwriting it.`,
      });
      continue;
    }

    try {
      // -B: a re-run for the same findings restarts the branch from the current base.
      await safeExeca("git", ["checkout", "-B", branchName], { cwd, stdio: "pipe" });
      branchCreated = true;
      await stageRunChanges(cwd, group);

      const hasStaged = await ensureRepoHasStagedChanges(cwd);
      if (!hasStaged) {
        results.push({
          provider,
          grouping,
          repository: options.repository,
          branchName: "",
          title,
          body,
          created: false,
          cveIds: plan.cveIds,
          packageNames: plan.packageNames,
          error: "No repository changes to include in change request.",
        });
        continue;
      }

      await safeExeca(
        "git",
        [
          "-c",
          `user.name=${BOT_NAME}`,
          "-c",
          `user.email=${BOT_EMAIL}`,
          "commit",
          "-m",
          commitMessage(title, group),
        ],
        { cwd, stdio: "pipe" },
      );

      // A re-run replaces only the commit a previous run pushed, and only if nobody moved the branch since.
      const pushArgs = withAuth(
        token,
        existing.remoteSha
          ? ["push", `--force-with-lease=refs/heads/${branchName}:${existing.remoteSha}`, "-u", pushRemote, branchName]
          : ["push", "-u", pushRemote, branchName],
      );
      await safeExeca("git", pushArgs, { cwd, stdio: "pipe" });

      const url =
        provider === "github"
          ? await createGitHubRequest({
              cwd,
              repository: options.repository,
              head: branchName,
              base: baseBranch,
              title,
              body,
              draft: options.draft,
              token,
              githubApiUrl: options.githubApiUrl,
            })
          : await createGitLabRequest({
              cwd,
              repository: options.repository,
              source: branchName,
              target: baseBranch,
              title,
              body,
              draft: options.draft,
            });

      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName,
        title,
        body,
        created: true,
        ...(existing.remoteSha ? { updated: true } : {}),
        draft: options.draft,
        url,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
      });
    } catch (error) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        draft: options.draft,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: error instanceof Error ? error.message : String(error),
      });
    } finally {
      if (branchCreated) {
        await safeExeca("git", ["checkout", baseBranch], { cwd, stdio: "pipe" }).catch(() => {});
      }
    }
  }

  return results;
}
