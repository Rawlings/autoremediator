import { execa } from "execa";
import { randomBytes } from "node:crypto";
import type {
  ChangeRequestGrouping,
  ChangeRequestOptions,
  ChangeRequestResult,
  RemediationReport,
} from "../../platform/types.js";

interface ChangeRequestPlan {
  cveIds: string[];
  packageNames: string[];
  title: string;
  body: string;
}

function sanitizeBranchToken(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9._/-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function buildPlan(reports: RemediationReport[]): ChangeRequestPlan {
  const cveIds = Array.from(new Set(reports.map((report) => report.cveId)));
  const packageNames = Array.from(
    new Set(reports.flatMap((report) => report.results.map((result) => result.packageName))),
  );

  const titleSuffix = cveIds.length === 1 ? cveIds[0]! : `${cveIds.length} CVEs`;
  const title = `security remediation: ${titleSuffix}`;
  const body = [
    "Automated remediation generated by autoremediator.",
    "",
    `CVEs: ${cveIds.join(", ")}`,
    `Packages: ${packageNames.join(", ")}`,
  ].join("\n");

  return {
    cveIds,
    packageNames,
    title,
    body,
  };
}

function resolveProvider(options: ChangeRequestOptions): "github" | "gitlab" {
  return options.provider ?? "github";
}

function resolveGrouping(options: ChangeRequestOptions): ChangeRequestGrouping {
  const allowed: ChangeRequestGrouping[] = ["all", "per-cve", "per-package", "by-severity"];
  if (options.grouping && !allowed.includes(options.grouping)) {
    throw new Error(
      `Unsupported changeRequest.grouping: "${options.grouping}". Supported values: ${allowed.join(", ")}`,
    );
  }
  return options.grouping ?? "all";
}

export function groupReports(
  reports: RemediationReport[],
  grouping: ChangeRequestGrouping,
): RemediationReport[][] {
  if (reports.length === 0) return [];
  if (grouping === "all") {
    return [reports];
  }

  if (grouping === "per-cve") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const key = report.cveId.toUpperCase();
      const list = map.get(key) ?? [];
      list.push(report);
      map.set(key, list);
    }
    return Array.from(map.values());
  }

  if (grouping === "per-package") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const pkgs = new Set(report.results.map((r) => r.packageName));
      if (pkgs.size === 0) {
        const list = map.get("misc") ?? [];
        list.push(report);
        map.set("misc", list);
      } else {
        for (const pkg of pkgs) {
          const list = map.get(pkg) ?? [];
          list.push(report);
          map.set(pkg, list);
        }
      }
    }
    return Array.from(map.values());
  }

  if (grouping === "by-severity") {
    const map = new Map<string, RemediationReport[]>();
    for (const report of reports) {
      const sev = report.cveDetails?.severity ?? "UNKNOWN";
      const list = map.get(sev) ?? [];
      list.push(report);
      map.set(sev, list);
    }
    return Array.from(map.values());
  }

  return [reports];
}

async function detectCurrentBranch(cwd: string): Promise<string> {
  const result = await execa("git", ["rev-parse", "--abbrev-ref", "HEAD"], {
    cwd,
    stdio: "pipe",
  });
  return result.stdout.trim();
}

async function ensureRepoHasChanges(cwd: string): Promise<boolean> {
  const diff = await execa("git", ["status", "--porcelain"], {
    cwd,
    stdio: "pipe",
  });
  return diff.stdout.trim().length > 0;
}

function toBranchName(prefix: string, cveIds: string[]): string {
  const token = sanitizeBranchToken(cveIds.join("-") || "remediation");
  return `${sanitizeBranchToken(prefix)}/${token}-${randomBytes(6).toString("hex")}`;
}

async function detectRepoFromRemote(cwd: string): Promise<string | undefined> {
  const result = await execa("git", ["config", "--get", "remote.origin.url"], {
    cwd,
    stdio: "pipe",
  }).catch(() => ({ stdout: "" }));
  const url = result.stdout.trim();
  const match = url.match(/[:/]([^/]+)\/([^/]+?)(?:\.git)?$/);
  if (match) {
    return `${match[1]}/${match[2]}`;
  }
  return undefined;
}

async function ensureRepoHasStagedChanges(cwd: string): Promise<boolean> {
  const result = await execa("git", ["diff", "--cached", "--name-only"], {
    cwd,
    stdio: "pipe",
  }).catch(() => ({ stdout: "" }));
  return result.stdout.trim().length > 0;
}

async function createGitHubRequest(params: {
  cwd: string;
  repository?: string;
  head: string;
  base: string;
  title: string;
  body: string;
  draft?: boolean;
  token?: string;
  githubApiUrl?: string;
}): Promise<string | undefined> {
  const token = params.token ?? process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;

  let repository = params.repository;
  if (!repository) {
    repository = await detectRepoFromRemote(params.cwd);
  }

  if (token && repository) {
    const [owner, repo] = repository.split("/");
    const baseUrl = params.githubApiUrl?.replace(/\/+$/, "") || "https://api.github.com";
    const endpoint = `${baseUrl}/repos/${owner}/${repo}/pulls`;
    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        authorization: `Bearer ${token}`,
        accept: "application/vnd.github+json",
        "content-type": "application/json",
        "user-agent": "autoremediator",
        "x-github-api-version": "2022-11-28",
      },
      body: JSON.stringify({
        title: params.title,
        head: params.head,
        base: params.base,
        body: params.body,
        draft: Boolean(params.draft),
      }),
    });

    if (!response.ok) {
      const errText = await response.text().catch(() => "");
      throw new Error(`GitHub API create pull request failed (${response.status}): ${errText}`);
    }

    const data = (await response.json()) as { html_url?: string };
    return data.html_url || undefined;
  }

  const args = [
    "pr",
    "create",
    "--head",
    params.head,
    "--base",
    params.base,
    "--title",
    params.title,
    "--body",
    params.body,
  ];
  if (params.repository) {
    args.push("--repo", params.repository);
  }
  if (params.draft) {
    args.push("--draft");
  }

  const result = await execa("gh", args, {
    cwd: params.cwd,
    stdio: "pipe",
  });
  return result.stdout.trim() || undefined;
}

async function createGitLabRequest(params: {
  cwd: string;
  repository?: string;
  source: string;
  target: string;
  title: string;
  body: string;
  draft?: boolean;
}): Promise<string | undefined> {
  const args = [
    "mr",
    "create",
    "--source-branch",
    params.source,
    "--target-branch",
    params.target,
    "--title",
    params.title,
    "--description",
    params.body,
  ];
  if (params.repository) {
    args.push("-R", params.repository);
  }
  if (params.draft) {
    args.push("--draft");
  }

  const result = await execa("glab", args, {
    cwd: params.cwd,
    stdio: "pipe",
  });
  return result.stdout.trim() || undefined;
}

export async function createChangeRequestsForReports(params: {
  cwd: string;
  options: ChangeRequestOptions;
  reports: RemediationReport[];
}): Promise<ChangeRequestResult[]> {
  const { cwd, options, reports } = params;
  const provider = resolveProvider(options);
  const grouping = resolveGrouping(options);
  const groups = groupReports(reports, grouping);

  if (groups.length === 0) {
    return [];
  }

  const results: ChangeRequestResult[] = [];
  const token =
    options.token ??
    (options.tokenEnvVar ? process.env[options.tokenEnvVar] : undefined) ??
    process.env.GITHUB_TOKEN ??
    process.env.GH_TOKEN;

  const baseBranch = options.baseBranch ?? (await detectCurrentBranch(cwd).catch(() => "main"));
  const branchPrefix = options.branchPrefix ?? "autoremediator";
  const pushRemote = options.pushRemote ?? "origin";
  if (options.pushRemote && !/^[a-zA-Z0-9._-]+$/.test(options.pushRemote)) {
    throw new Error(`Invalid pushRemote value: ${options.pushRemote}`);
  }
  if (options.repository && !/^[a-zA-Z0-9._-]+\/[a-zA-Z0-9._-]+$/.test(options.repository)) {
    throw new Error(`Invalid repository format: ${options.repository}`);
  }

  for (const group of groups) {
    const plan = buildPlan(group);
    const titlePrefix = options.titlePrefix?.trim().slice(0, 200);
    const bodyFooter = options.bodyFooter ? options.bodyFooter.slice(0, 2000) : undefined;
    const title = titlePrefix ? `${titlePrefix} ${plan.title}` : plan.title;
    const body = bodyFooter ? `${plan.body}\n\n${bodyFooter}` : plan.body;

    const hasChanges = await ensureRepoHasChanges(cwd).catch(() => false);
    if (!hasChanges) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: "No repository changes to include in change request.",
      });
      continue;
    }

    const branchName = toBranchName(branchPrefix, plan.cveIds);
    let branchCreated = false;

    try {
      await execa("git", ["checkout", "-b", branchName], { cwd, stdio: "pipe" });
      branchCreated = true;
      await execa("git", ["add", "-A"], { cwd, stdio: "pipe" });

      const hasStaged = await ensureRepoHasStagedChanges(cwd);
      if (!hasStaged) {
        results.push({
          provider,
          grouping,
          repository: options.repository,
          branchName: "",
          title,
          body,
          created: false,
          cveIds: plan.cveIds,
          packageNames: plan.packageNames,
          error: "No repository changes to include in change request.",
        });
        continue;
      }

      await execa(
        "git",
        [
          "-c",
          "user.name=autoremediator[bot]",
          "-c",
          "user.email=41898282+github-actions[bot]@users.noreply.github.com",
          "commit",
          "-m",
          title,
        ],
        { cwd, stdio: "pipe" },
      );

      const pushArgs = token
        ? [
            "-c",
            `http.extraheader=AUTHORIZATION: basic ${Buffer.from(`x-access-token:${token}`).toString("base64")}`,
            "push",
            "-u",
            pushRemote,
            branchName,
          ]
        : ["push", "-u", pushRemote, branchName];
      await execa("git", pushArgs, { cwd, stdio: "pipe" });

      const url =
        provider === "github"
          ? await createGitHubRequest({
              cwd,
              repository: options.repository,
              head: branchName,
              base: baseBranch,
              title,
              body,
              draft: options.draft,
              token,
              githubApiUrl: options.githubApiUrl,
            })
          : await createGitLabRequest({
              cwd,
              repository: options.repository,
              source: branchName,
              target: baseBranch,
              title,
              body,
              draft: options.draft,
            });

      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName,
        title,
        body,
        created: true,
        draft: options.draft,
        url,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
      });
    } catch (error) {
      results.push({
        provider,
        grouping,
        repository: options.repository,
        branchName: "",
        title,
        body,
        created: false,
        draft: options.draft,
        cveIds: plan.cveIds,
        packageNames: plan.packageNames,
        error: error instanceof Error ? error.message : String(error),
      });
    } finally {
      if (branchCreated) {
        await execa("git", ["checkout", baseBranch], { cwd, stdio: "pipe" }).catch(() => {});
      }
    }
  }

  return results;
}
