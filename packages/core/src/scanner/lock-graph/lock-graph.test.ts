const CASES: Array<[string, string, string, boolean]> = [
  ["npm v3", "package-lock.json", NPM, true],
  ["npm v1", "package-lock.json", NPM_V1, false],
  ["pnpm v9", "pnpm-lock.yaml", PNPM_V9, true],
  ["pnpm v5", "pnpm-lock.yaml", PNPM_V5, true],
  ["yarn classic", "yarn.lock", YARN_V1, false],
  ["yarn berry", "yarn.lock", YARN_BERRY, false],
  ["bun", "bun.lock", BUN, false],
];

describe.each(CASES)("lock graph: %s", (_label, file, content, recordsInstallScripts) => {
  const graph = parseLockGraph(file, content, MANIFEST)!;
  const evil = findOccurrences(graph, inRange("evil", "*"));

  it("lists every locked version of a package", () => {
    expect(versionsOfPackage(graph, "evil").toSorted()).toEqual(["1.2.3", "1.2.4"]);
    expect(versionsOfPackage(graph, "nothing")).toEqual([]);
  });

  it("tells production from development and gives the parent chain", () => {
    const prod = evil.find((occurrence) => occurrence.version === "1.2.3")!;
    expect(prod).toMatchObject({ scope: "production", direct: false });
    expect(prod.via).toEqual([".", "a@1.0.0", "b@1.0.0", "evil@1.2.3"]);
    expect(prod.dependents).toEqual(["b@1.0.0"]);

    const dev = evil.find((occurrence) => occurrence.version === "1.2.4")!;
    expect(dev).toMatchObject({ scope: "development", direct: false });
    expect(dev.via).toEqual([".", "d@1.0.0", "evil@1.2.4"]);
  });

  it("marks direct dependencies and honours the range", () => {
    const direct = findOccurrences(graph, inRange("a", "^1"));
    expect(direct).toHaveLength(1);
    expect(direct[0]).toMatchObject({
      direct: true,
      scope: "production",
      workspaces: ["."],
      via: [".", "a@1.0.0"],
    });
    expect(findOccurrences(graph, inRange("evil", ">=1.2.4"))).toHaveLength(1);
    expect(findOccurrences(graph, inRange("evil", "<1.2.3"))).toEqual([]);
  });

  it(`${recordsInstallScripts ? "reads" : "cannot read"} install-script flags from the lockfile`, () => {
    const prod = evil.find((occurrence) => occurrence.version === "1.2.3")!;
    const dev = evil.find((occurrence) => occurrence.version === "1.2.4")!;
    expect(prod.installScript).toBe(recordsInstallScripts ? true : undefined);
    expect(dev.installScript).toBe(recordsInstallScripts ? false : undefined);
  });
});

describe("lock graph edge cases", () => {
  it("ignores files that are not lockfiles and rejects malformed ones", () => {
    expect(parseLockGraph("package.json", "{}")).toBeUndefined();
    expect(() => parseLockGraph("package-lock.json", "not json")).toThrow();
    expect(() => parseLockGraph("pnpm-lock.yaml", "- just\n- a list")).toThrow(/YAML mapping/);
  });

  it("walks npm workspaces and finds a package only a workspace asks for", () => {
    const lock = JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "": { name: "root", workspaces: ["packages/*"] },
        "node_modules/web": { resolved: "packages/web", link: true },
        "packages/web": { name: "web", version: "1.0.0", dependencies: { evil: "1.2.3" } },
        "node_modules/evil": { version: "1.2.3" },
      },
    });
    const [hit] = findOccurrences(
      parseLockGraph("package-lock.json", lock)!,
      inRange("evil", "1.2.3"),
    );
    expect(hit).toMatchObject({
      direct: true,
      scope: "production",
      workspaces: ["packages/web"],
      via: ["packages/web", "evil@1.2.3"],
    });
  });

  it("flags a locked package nothing leads to", () => {
    const lock = JSON.stringify({
      lockfileVersion: 3,
      packages: { "": { dependencies: {} }, "node_modules/orphan": { version: "1.0.0" } },
    });
    const [hit] = findOccurrences(
      parseLockGraph("package-lock.json", lock)!,
      inRange("orphan", "*"),
    );
    expect(hit).toMatchObject({ scope: "unreferenced", direct: false, via: [] });
  });

  it("strips JSONC comments and trailing commas but leaves strings alone", () => {
    expect(
      JSON.parse(stripJsonc('{ "a": "x, } // not a comment", /* c */ "b": [1, 2,], }')),
    ).toEqual({
      a: "x, } // not a comment",
      b: [1, 2],
    });
  });

  it("copes with a cyclic graph", () => {
    const lock = JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "": { dependencies: { x: "1.0.0" } },
        "node_modules/x": { version: "1.0.0", dependencies: { y: "1.0.0" } },
        "node_modules/y": { version: "1.0.0", dependencies: { x: "1.0.0" } },
      },
    });
    const [hit] = findOccurrences(parseLockGraph("package-lock.json", lock)!, inRange("y", "*"));
    expect(hit?.via).toEqual([".", "x@1.0.0", "y@1.0.0"]);
  });
});
