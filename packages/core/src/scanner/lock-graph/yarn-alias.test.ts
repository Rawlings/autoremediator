import { describe, expect, it } from "vitest";

import { parseYarnLock } from "./yarn.js";

const CLASSIC = `# yarn lockfile v1

"@org/real@^2.0.0", "@org/alias@npm:@org/real@^2.0.0":
  version "2.1.0"
  resolved "https://registry.yarnpkg.com/@org/real/-/real-2.1.0.tgz#abc"

"foo@npm:bar@^1.0.0":
  version "1.0.0"
  resolved "https://registry.yarnpkg.com/bar/-/bar-1.0.0.tgz#def"
  dependencies:
    baz "^3.0.0"

baz@^3.0.0:
  version "3.0.0"
  resolved "https://registry.yarnpkg.com/baz/-/baz-3.0.0.tgz#ghi"
`;

const BERRY = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0

"foo@npm:bar@^1.0.0":
  version: 1.0.0
  resolution: "bar@npm:1.0.0"
  dependencies:
    baz: ^3.0.0
  checksum: 10c0/aaa
  languageName: node
  linkType: hard

"short@npm:@org/real@^2.0.0":
  version: 2.1.0
  resolution: "@org/real@npm:2.1.0"
  checksum: 10c0/bbb
  languageName: node
  linkType: hard

"baz@npm:^3.0.0":
  version: 3.0.0
  resolution: "baz@npm:3.0.0"
  checksum: 10c0/ccc
  languageName: node
  linkType: hard
`;

describe("yarn.lock aliases", () => {
  it("names a classic npm: alias by the package it installs, not by the alias", () => {
    const graph = parseYarnLock(CLASSIC, { dependencies: { foo: "npm:bar@^1.0.0", baz: "^3.0.0" } });
    expect([...graph.nodes.keys()].toSorted()).toEqual(["@org/real@2.1.0", "bar@1.0.0", "baz@3.0.0"]);
    expect(graph.nodes.get("bar@1.0.0")).toMatchObject({ name: "bar", version: "1.0.0", deps: ["baz@3.0.0"] });
    expect(graph.nodes.has("foo@1.0.0")).toBe(false);
    expect(graph.roots[0]?.prod).toEqual(["bar@1.0.0", "baz@3.0.0"]);
  });

  it("names a berry alias by its resolution, scoped names included", () => {
    const graph = parseYarnLock(BERRY, { dependencies: { foo: "npm:bar@^1.0.0", short: "npm:@org/real@^2.0.0" } });
    expect([...graph.nodes.keys()].toSorted()).toEqual(["@org/real@2.1.0", "bar@1.0.0", "baz@3.0.0"]);
    expect(graph.nodes.get("bar@1.0.0")).toMatchObject({ name: "bar", deps: ["baz@3.0.0"] });
    expect(graph.roots[0]?.prod).toEqual(["bar@1.0.0", "@org/real@2.1.0"]);
  });

  it("still names ordinary entries by their descriptor", () => {
    const graph = parseYarnLock(BERRY, { dependencies: { baz: "^3.0.0" } });
    expect(graph.nodes.get("baz@3.0.0")?.name).toBe("baz");
    expect(graph.roots[0]?.prod).toEqual(["baz@3.0.0"]);
  });
});
