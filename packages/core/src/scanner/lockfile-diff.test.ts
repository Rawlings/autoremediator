import { describe, expect, it } from "vitest";
import { computeLockfileDiff, parseLockfileDependencies } from "./lockfile-diff.js";

describe("lockfile-diff", () => {
  describe("package-lock.json", () => {
    it("parses npm v2/v3 packages section", () => {
      const lock = JSON.stringify({
        name: "my-app",
        version: "1.0.0",
        lockfileVersion: 3,
        packages: {
          "": { name: "my-app" },
          "node_modules/lodash": { version: "4.17.20" },
          "node_modules/@scope/pkg": { version: "1.2.3" },
          "node_modules/direct/node_modules/nested": { version: "2.0.0" },
        },
      });

      const deps = parseLockfileDependencies("package-lock.json", lock);
      expect(deps.get("lodash")?.has("4.17.20")).toBe(true);
      expect(deps.get("@scope/pkg")?.has("1.2.3")).toBe(true);
      expect(deps.get("nested")?.has("2.0.0")).toBe(true);
    });

    it("computes diff between old and new package-lock.json", () => {
      const oldLock = JSON.stringify({
        lockfileVersion: 3,
        packages: {
          "node_modules/semver": { version: "7.5.0" },
          "node_modules/removed-pkg": { version: "1.0.0" },
        },
      });
      const newLock = JSON.stringify({
        lockfileVersion: 3,
        packages: {
          "node_modules/semver": { version: "7.6.0" },
          "node_modules/added-pkg": { version: "2.0.0" },
        },
      });

      const diff = computeLockfileDiff("package-lock.json", oldLock, newLock);
      expect(diff).toEqual(
        expect.arrayContaining([
          expect.objectContaining({
            packageName: "semver",
            changeType: "upgraded",
            oldVersion: "7.5.0",
            newVersion: "7.6.0",
            dependencyType: "transitive",
          }),
          expect.objectContaining({
            packageName: "added-pkg",
            changeType: "added",
            newVersion: "2.0.0",
            dependencyType: "transitive",
          }),
          expect.objectContaining({
            packageName: "removed-pkg",
            changeType: "removed",
            oldVersion: "1.0.0",
            dependencyType: "transitive",
          }),
        ]),
      );
    });
  });

  describe("pnpm-lock.yaml", () => {
    it("parses pnpm lockfile packages", () => {
      const lock = `
lockfileVersion: '6.0'
packages:
  /@babel/core@7.20.0:
    resolution: {integrity: sha512-...}
  /lodash@4.17.21:
    resolution: {integrity: sha512-...}
  /react-dom@18.2.0(react@18.2.0):
    resolution: {integrity: sha512-...}
`;
      const deps = parseLockfileDependencies("pnpm-lock.yaml", lock);
      expect(deps.get("@babel/core")?.has("7.20.0")).toBe(true);
      expect(deps.get("lodash")?.has("4.17.21")).toBe(true);
      expect(deps.get("react-dom")?.has("18.2.0")).toBe(true);
    });

    it("computes pnpm lockfile diff", () => {
      const oldLock = `
lockfileVersion: '6.0'
packages:
  /lodash@4.17.19:
    resolution: {integrity: sha512-...}
`;
      const newLock = `
lockfileVersion: '6.0'
packages:
  /lodash@4.17.21:
    resolution: {integrity: sha512-...}
`;
      const diff = computeLockfileDiff("pnpm-lock.yaml", oldLock, newLock);
      expect(diff).toHaveLength(1);
      expect(diff[0]).toMatchObject({
        packageName: "lodash",
        changeType: "upgraded",
        oldVersion: "4.17.19",
        newVersion: "4.17.21",
        dependencyType: "transitive",
      });
    });
  });

  describe("yarn.lock", () => {
    it("parses yarn lock v1 format", () => {
      const lock = `
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT DIRECTLY.
# yarn lockfile v1

"lodash@^4.17.0", "lodash@^4.17.20":
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"

"@scope/my-pkg@^1.0.0":
  version "1.0.2"
  resolved "https://registry.yarnpkg.com/@scope/my-pkg/-/my-pkg-1.0.2.tgz"
`;
      const deps = parseLockfileDependencies("yarn.lock", lock);
      expect(deps.get("lodash")?.has("4.17.21")).toBe(true);
      expect(deps.get("@scope/my-pkg")?.has("1.0.2")).toBe(true);
    });
  });
});
